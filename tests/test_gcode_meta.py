"""read_gcode_meta against the two layouts OrcaSlicer writes (GCode.cpp): the config block + stats at the END of the file
for a Klipper printer like the SV08 MAX, and the config block at the TOP for a Bambu printer."""

import tempfile
import unittest
from pathlib import Path

from makeros_hub.printers import gcode_meta
from makeros_hub.printers.gcode_meta import read_gcode_meta


def sv08_gcode(*, mm="1520.31", g="4.53", types="PLA", colours="#FFFFFF", model="Sovol SV08 MAX", config=True) -> str:
    """The tail of a real OrcaSlicer SV08 MAX G-code, trimmed (stats, then the config block)."""
    lines = [
        "; HEADER_BLOCK_START",
        "; generated by OrcaSlicer 2.4.2 on 2026-10-14 at 10:00:00",
        "; HEADER_BLOCK_END",
        "G28",
        "G1 X10 Y10 E1.2 ; not a comment we read",
        "; EXECUTABLE_BLOCK_END",
        "",
        f"; filament used [mm] = {mm}",
        "; filament used [cm3] = 3.66",
    ]
    if g is not None:
        lines.append(f"; filament used [g] = {g}")
    lines += ["; filament cost = 0.09", "; total filament used [g] = 999.99", "; estimated printing time (normal mode) = 1h 2m 3s"]
    if config:
        lines += [
            "; CONFIG_BLOCK_START",
            "; filament_settings_id = \"Generic PLA @Sovol SV08 MAX\"",
            f"; filament_colour = {colours}",
            f"; filament_type = {types}",
            "; host_type = octoprint",
            f"; printer_model = {model}",
            "; start_gcode = START_PRINT EXTRUDER_TEMP=[nozzle_temperature_initial_layer] BED_TEMP=[bed_temperature]",
            "; CONFIG_BLOCK_END",
        ]
    return "\n".join(lines) + "\n"


class TestReadGcodeMeta(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def write(self, text: str, name: str = "cube.gcode") -> Path:
        path = Path(self.tmp.name) / name
        path.write_text(text, encoding="utf-8")
        return path

    def test_tail_layout_sv08(self):
        meta = read_gcode_meta(self.write(sv08_gcode()))
        self.assertEqual(meta["printerModel"], "Sovol SV08 MAX")
        self.assertEqual(meta["requiredFilaments"], [{"slot": 1, "type": "PLA", "color": "FFFFFFFF", "usedG": 4.53}])
        self.assertEqual(meta["estGrams"], 5)   # ceil, never rounded down to a cheaper print

    def test_head_layout_beyond_the_tail_window(self):
        # Bambu-style: the config block right after the header; stats at the end; more than one window of moves between.
        head = "\n".join(["; HEADER_BLOCK_START", "; HEADER_BLOCK_END", "; CONFIG_BLOCK_START",
                          "; printer_model = Bambu Lab A1 mini", "; filament_type = PETG", "; filament_colour = #00FF00",
                          "; CONFIG_BLOCK_END"]) + "\n"
        moves = "G1 X1 Y1 E0.1\n" * (gcode_meta.WINDOW_BYTES // 14 + 10)
        tail = "; filament used [mm] = 300.00\n; filament used [g] = 0.90\n"
        meta = read_gcode_meta(self.write(head + moves + tail))
        self.assertEqual(meta["printerModel"], "Bambu Lab A1 mini")
        self.assertEqual(meta["requiredFilaments"], [{"slot": 1, "type": "PETG", "color": "00FF00FF", "usedG": 0.9}])
        self.assertEqual(meta["estGrams"], 1)

    def test_only_slots_that_print_are_required(self):
        meta = read_gcode_meta(self.write(sv08_gcode(mm="0.00, 12.34", g="0.00, 37.21", types="PLA;PETG", colours="#FFFFFF;#000000")))
        self.assertEqual(meta["requiredFilaments"], [{"slot": 2, "type": "PETG", "color": "000000FF", "usedG": 37.21}])
        self.assertEqual(meta["estGrams"], 38)

    def test_no_grams_line_means_no_estimate(self):
        # "total filament used [g]" is still in the file: an exact key match must not take it for the per-filament line.
        meta = read_gcode_meta(self.write(sv08_gcode(g=None)))
        self.assertEqual(meta["requiredFilaments"], [{"slot": 1, "type": "PLA", "color": "FFFFFFFF"}])
        self.assertIsNone(meta["estGrams"])

    def test_no_config_block_has_no_model(self):
        meta = read_gcode_meta(self.write(sv08_gcode(config=False)))
        self.assertIsNone(meta["printerModel"])

    def test_non_gcode_suffix_is_not_parsed(self):
        self.assertIsNone(read_gcode_meta(self.write(sv08_gcode(), name="cube.gcode.3mf")))
        self.assertIsNotNone(read_gcode_meta(self.write(sv08_gcode(), name="cube.GCO")))


if __name__ == "__main__":
    unittest.main()
